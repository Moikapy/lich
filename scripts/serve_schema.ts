// scripts/serve_schema.ts — JSON Schema export of the serve wire protocol.
//
// usage: bun scripts/serve_schema.ts
//
// generates schemas/serve-protocol.schema.json from the exported types in
// src/serve/protocol.ts so non-TS clients can validate frames. the output
// is checked in; test/serve_schema.test.ts fails when it is stale.

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createGenerator } from "ts-json-schema-generator";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const serve_schema_path = resolve(root, "schemas/serve-protocol.schema.json");

export function build_serve_schema(): string {
  const schema = createGenerator({
    path: resolve(root, "src/serve/protocol.ts"),
    tsconfig: resolve(root, "tsconfig.json"),
    type: "*",
    expose: "export",
    skipTypeCheck: true,
  }).createSchema("*");
  return `${JSON.stringify({ $comment: "Generated by scripts/serve_schema.ts from src/serve/protocol.ts. Do not edit.", ...schema }, null, 2)}\n`;
}

if (import.meta.main) {
  writeFileSync(serve_schema_path, build_serve_schema());
  console.log("[serve_schema] wrote schemas/serve-protocol.schema.json");
}
