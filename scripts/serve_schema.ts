// scripts/serve_schema.ts — JSON Schema export of the serve wire protocol.
//
// usage: bun scripts/serve_schema.ts
//
// generates schemas/serve-protocol.schema.json from the exported types in
// src/serve/protocol.ts so non-TS clients can validate frames. the output
// is checked in; test/serve_schema.test.ts fails when it is stale.

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createGenerator } from "ts-json-schema-generator";
import { SERVE_METHODS } from "../src/serve/protocol.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const serve_schema_path = resolve(root, "schemas/serve-protocol.schema.json");

export function build_serve_schema(): string {
  const schema = createGenerator({
    path: resolve(root, "src/serve/protocol.ts"),
    tsconfig: resolve(root, "tsconfig.json"),
    type: "*",
    expose: "export",
    skipTypeCheck: true,
  }).createSchema("*");
  // the generator skips the generic ServeRequest / ServeSuccess aliases, so
  // build them per method from ServeMethodMap: `method` pins `params`.
  const defs = schema.definitions as Record<string, any>;
  const map = defs.ServeMethodMap.properties;
  const envelope = (properties: Record<string, unknown>) => ({
    type: "object",
    properties: { jsonrpc: { type: "string", const: "2.0" }, id: { $ref: "#/definitions/JsonRpcId" }, ...properties },
    required: ["jsonrpc", "id", ...Object.keys(properties)],
    additionalProperties: false,
  });
  defs.ServeRequest = {
    description: "A client request: `method` pins `params`.",
    anyOf: SERVE_METHODS.map((m) => envelope({ method: { type: "string", const: m }, params: map[m].properties.params })),
  };
  defs.ServeSuccess = {
    description: "A successful response; `result` is one of the per-method results.",
    anyOf: SERVE_METHODS.map((m) => envelope({ result: map[m].properties.result })),
  };
  defs.ServeFrame = {
    description: "Any frame on the serve socket: a client request, or a server success, error or event.",
    anyOf: ["ServeRequest", "ServeSuccess", "JsonRpcError", "ServeEventNotification"].map((d) => ({ $ref: `#/definitions/${d}` })),
  };
  return `${JSON.stringify({ $comment: "Generated by scripts/serve_schema.ts from src/serve/protocol.ts. Do not edit.", $schema: schema.$schema, $ref: "#/definitions/ServeFrame", definitions: defs }, null, 2)}\n`;
}

if (import.meta.main) {
  writeFileSync(serve_schema_path, build_serve_schema());
  console.log("[serve_schema] wrote schemas/serve-protocol.schema.json");
}
